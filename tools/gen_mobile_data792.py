"""Generates mods/client_mobile/data792.lua from a Sabrehaven (7.92) server's
data files: the spells players can cast (for the hotbar's spell list) and
names for runes and carryable items (the 7.92 client data has no names).

    python3 tools/gen_mobile_data792.py SERVER_DATA_DIR > mods/client_mobile/data792.lua

SERVER_DATA_DIR is the server's data directory (with spells/spells.xml and
items792/items.srv).
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

# Promoted vocations count as their base vocation (client vocation ids 1-4)
VOCATIONS = {
    "Sorcerer": 1, "Master Sorcerer": 1,
    "Druid": 2, "Elder Druid": 2,
    "Paladin": 3, "Royal Paladin": 3,
    "Knight": 4, "Elite Knight": 4,
}


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def display_name(name):
    name = re.sub(r"^(a|an|some|the) ", "", name)
    return name[:1].upper() + name[1:]


def main():
    data_dir = sys.argv[1]
    spells = ET.parse(os.path.join(data_dir, "spells", "spells.xml")).getroot()

    out = ["-- Generated by tools/gen_mobile_data792.py from the server's spells.xml and",
           "-- items.srv. Do not edit by hand.",
           "Data792 = {}", "", "Data792.spells = {"]
    for spell in spells:
        if spell.tag not in ("instant", "conjure"):
            continue
        vocations = sorted({VOCATIONS[v.get("name")] for v in spell.findall("vocation") if v.get("name") in VOCATIONS})
        fields = [
            f"name = {lua_string(spell.get('name'))}",
            f"words = {lua_string(spell.get('words'))}",
            f"magicLevel = {int(spell.get('maglv', 0))}",
            f"level = {int(spell.get('lvl', 0))}",
            f"mana = {int(spell.get('mana', 0))}",
            f"soul = {int(spell.get('soul', 0))}",
            f"premium = {'true' if spell.get('prem') == '1' else 'false'}",
            f"param = {'true' if spell.get('params') == '1' else 'false'}",
            f"conjure = {'true' if spell.tag == 'conjure' else 'false'}",
            "vocations = {" + ", ".join(map(str, vocations)) + "}",
        ]
        out.append("    { " + ", ".join(fields) + " },")
    out.append("}")

    out += ["", "-- Rune names by item id", "Data792.runes = {"]
    runes = {}
    for rune in spells.findall("rune"):
        name = rune.get("name")
        runes[int(rune.get("id"))] = name if name.lower().endswith(" rune") else name + " Rune"
    for item_id in sorted(runes):
        out.append(f"    [{item_id}] = {lua_string(runes[item_id])},")
    out.append("}")

    # Item names, for items that can be picked up (Take flag)
    out += ["", "-- Names of items that can be carried, by item id", "Data792.items = {"]
    text = open(os.path.join(data_dir, "items792", "items.srv"), encoding="latin-1").read()
    for block in re.split(r"\n\s*\n", text):
        type_id = re.search(r"^TypeID\s*=\s*(\d+)", block, re.M)
        name = re.search(r'^Name\s*=\s*"([^"]*)"', block, re.M)
        flags = re.search(r"^Flags\s*=\s*\{([^}]*)\}", block, re.M)
        if type_id and name and name.group(1) and flags and "Take" in flags.group(1).split(","):
            out.append(f"    [{type_id.group(1)}] = {lua_string(display_name(name.group(1)))},")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
